package com.interviewtrainer.question;

import com.interviewtrainer.session.PracticeSession;
import com.interviewtrainer.topic.Topic;
import jakarta.persistence.CollectionTable;
import jakarta.persistence.Column;
import jakarta.persistence.ElementCollection;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OrderColumn;
import jakarta.persistence.PrePersist;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;

import java.time.Instant;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Objects;

/**
 * A practice question generated by the LLM for a topic and level. A follow-up question points to
 * the question it digs deeper into via {@link #getParent()}.
 */
@Entity
@Table(name = "question", uniqueConstraints = @UniqueConstraint(columnNames = {"session_id", "position"}))
public class Question {

    public static final int MAX_TEXT_LENGTH = 4000;

    @Id
    @GeneratedValue(strategy = GenerationType.SEQUENCE)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "topic_id", nullable = false)
    private Topic topic;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private Level level;

    @Column(nullable = false, length = MAX_TEXT_LENGTH)
    private String text;

    /** What a good answer should cover; the evaluation is measured against these. */
    @ElementCollection
    @CollectionTable(name = "question_key_points", joinColumns = @JoinColumn(name = "question_id"))
    @OrderColumn(name = "position")
    @Column(name = "key_point", nullable = false, length = 1000)
    private List<String> keyPoints = new ArrayList<>();

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "parent_id")
    private Question parent;

    /** The practice session this question was asked in; null for questions outside a session. */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "session_id")
    private PracticeSession session;

    /** 1-based order of the question within its session; null when there is no session. */
    private Integer position;

    @Column(nullable = false, updatable = false)
    private Instant createdAt;

    protected Question() {
    }

    /** A question outside any practice session. */
    public Question(Topic topic, Level level, String text, List<String> keyPoints) {
        this(null, null, topic, level, text, keyPoints, null);
    }

    /** A question asked as the {@code position}-th item of {@code session}. */
    public Question(PracticeSession session, int position, Topic topic, Level level, String text,
                    List<String> keyPoints) {
        this(Objects.requireNonNull(session, "session"), position, topic, level, text, keyPoints, null);
    }

    private Question(PracticeSession session, Integer position, Topic topic, Level level, String text,
                     List<String> keyPoints, Question parent) {
        if (session != null && (position == null || position < 1)) {
            throw new IllegalArgumentException("Position in a session must be 1 or greater");
        }
        this.session = session;
        this.position = session == null ? null : position;
        this.topic = Objects.requireNonNull(topic, "topic");
        this.level = Objects.requireNonNull(level, "level");
        if (text == null || text.isBlank()) {
            throw new IllegalArgumentException("Question text must not be blank");
        }
        this.text = text.strip();
        this.keyPoints = new ArrayList<>(keyPoints == null ? List.of() : keyPoints);
        this.parent = parent;
    }

    /**
     * Creates a follow-up with the same session, topic and level as {@code parent}.
     * {@code position} is its place in the session and is ignored when the parent has no session.
     */
    public static Question followUp(Question parent, Integer position, String text, List<String> keyPoints) {
        Objects.requireNonNull(parent, "parent");
        return new Question(parent.getSession(), position, parent.getTopic(), parent.getLevel(),
                text, keyPoints, parent);
    }

    @PrePersist
    void onCreate() {
        createdAt = Instant.now();
    }

    public boolean isFollowUp() {
        return parent != null;
    }

    public Long getId() {
        return id;
    }

    public Topic getTopic() {
        return topic;
    }

    public Level getLevel() {
        return level;
    }

    public String getText() {
        return text;
    }

    public List<String> getKeyPoints() {
        return Collections.unmodifiableList(keyPoints);
    }

    public Question getParent() {
        return parent;
    }

    public PracticeSession getSession() {
        return session;
    }

    public Integer getPosition() {
        return position;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }
}
